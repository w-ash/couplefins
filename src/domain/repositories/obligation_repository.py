from typing import Protocol
from uuid import UUID

from src.domain.entities.obligation import Obligation


class ObligationRepositoryProtocol(Protocol):
    async def get_by_id(self, id: UUID) -> Obligation | None: ...
    async def get_by_ids(self, ids: list[UUID]) -> list[Obligation]: ...
    # In due order.
    async def get_by_asset_id(self, asset_id: UUID) -> list[Obligation]: ...
    async def get_by_loan_id(self, loan_id: UUID) -> list[Obligation]: ...
    # The obligations that the given rows pay.
    async def get_by_paid_transaction_ids(
        self, transaction_ids: list[UUID]
    ) -> list[Obligation]: ...
    async def save(self, entity: Obligation) -> Obligation: ...
    async def save_batch(self, entities: list[Obligation]) -> list[Obligation]: ...
    async def delete(self, id: UUID) -> bool: ...
    async def delete_by_ids(self, ids: list[UUID]) -> int: ...
