from typing import Protocol
from uuid import UUID

from src.domain.entities.loan import Loan


class LoanRepositoryProtocol(Protocol):
    async def get_by_id(self, id: UUID) -> Loan | None: ...
    async def get_by_ids(self, ids: list[UUID]) -> list[Loan]: ...
    # In the order they were created.
    async def get_by_asset_id(self, asset_id: UUID) -> list[Loan]: ...
    async def get_by_slug(self, slug: str) -> Loan | None: ...
    # True when another loan names `loan_id` as its replacement.
    async def exists_replaced_by(self, loan_id: UUID) -> bool: ...
    async def save(self, entity: Loan) -> Loan: ...
    async def save_batch(self, entities: list[Loan]) -> list[Loan]: ...
    async def delete(self, id: UUID) -> bool: ...
